using Microsoft.EntityFrameworkCore;
using Veridoc.API.DTOs;
using Veridoc.API.Models;
using Veridoc.API.Validators;

namespace Veridoc.API.Data;

/// <summary>
/// Componente encargado de asegurar la creación del esquema en PostgreSQL (local o Supabase)
/// y poblar (seed) el catálogo inicial de tipos de documentos y reglas definidas en los validadores del MVP.
/// </summary>
public static class DbInitializer
{
    /// <summary>
    /// Sentencia DDL idempotente para crear las 4 tablas del MVP en el esquema <c>public</c>.
    /// Es indispensable para proveedores cloud como Supabase, donde <c>EnsureCreatedAsync()</c> omite
    /// la creación de tablas al detectar que la base de datos ya contiene esquemas internos (<c>auth</c>, <c>storage</c>).
    /// </summary>
    private const string EnsurePublicSchemaSql = """
        CREATE TABLE IF NOT EXISTS public.tipos_documento (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "Codigo" character varying(64) NOT NULL,
            "Nombre" character varying(150) NOT NULL,
            "Activo" boolean NOT NULL,
            "FechaCreacionUtc" timestamp with time zone NOT NULL
        );
        CREATE UNIQUE INDEX IF NOT EXISTS "IX_tipos_documento_Codigo"
            ON public.tipos_documento ("Codigo");

        CREATE TABLE IF NOT EXISTS public.reglas_validacion (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "TipoDocumentoId" integer NOT NULL REFERENCES public.tipos_documento ("Id") ON DELETE CASCADE,
            "Codigo" character varying(80) NOT NULL,
            "Nombre" character varying(150) NOT NULL,
            "Descripcion" character varying(500) NOT NULL,
            "Activa" boolean NOT NULL
        );
        CREATE UNIQUE INDEX IF NOT EXISTS "IX_reglas_validacion_TipoDocumentoId_Codigo"
            ON public.reglas_validacion ("TipoDocumentoId", "Codigo");

        CREATE TABLE IF NOT EXISTS public.validaciones (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "TipoDocumentoId" integer NULL REFERENCES public.tipos_documento ("Id") ON DELETE SET NULL,
            "CodigoTipoDocumento" character varying(64) NOT NULL,
            "EsValido" boolean NOT NULL,
            "TotalErrores" integer NOT NULL,
            "CorrelationId" character varying(64) NOT NULL,
            "FechaValidacionUtc" timestamp with time zone NOT NULL
        );
        CREATE INDEX IF NOT EXISTS "IX_validaciones_FechaValidacionUtc"
            ON public.validaciones ("FechaValidacionUtc");
        CREATE INDEX IF NOT EXISTS "IX_validaciones_CorrelationId"
            ON public.validaciones ("CorrelationId");

        CREATE TABLE IF NOT EXISTS public.detalles_error (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "ValidacionId" integer NOT NULL REFERENCES public.validaciones ("Id") ON DELETE CASCADE,
            "Campo" character varying(100) NOT NULL,
            "CodigoRegla" character varying(80) NOT NULL,
            "Mensaje" character varying(500) NOT NULL
        );
        CREATE INDEX IF NOT EXISTS "IX_detalles_error_ValidacionId"
            ON public.detalles_error ("ValidacionId");
        """;

    /// <summary>
    /// Intenta inicializar la base de datos y sincronizar el catálogo de reglas al arrancar la aplicación.
    /// Si PostgreSQL no está disponible, registra una advertencia controlada sin abortar el inicio de la API.
    /// </summary>
    /// <param name="serviceProvider">Proveedor de servicios de la aplicación.</param>
    public static async Task TryInitializeAsync(IServiceProvider serviceProvider)
    {
        using IServiceScope scope = serviceProvider.CreateScope();
        var configuration = scope.ServiceProvider.GetRequiredService<IConfiguration>();
        var loggerFactory = scope.ServiceProvider.GetRequiredService<ILoggerFactory>();
        ILogger logger = loggerFactory.CreateLogger("DbInitializer");

        string? connectionString = configuration.GetConnectionString("PostgreSqlConnection");
        if (string.IsNullOrWhiteSpace(connectionString))
        {
            logger.LogInformation("No se configuró 'PostgreSqlConnection'. La API operará sin inicialización automática de PostgreSQL.");
            return;
        }

        try
        {
            var dbContext = scope.ServiceProvider.GetRequiredService<VeridocDbContext>();
            var validators = scope.ServiceProvider.GetServices<IDocumentValidator>();

            await SeedCatalogAsync(dbContext, validators);
            logger.LogInformation("Esquema de PostgreSQL/Supabase y catálogo de reglas sincronizados correctamente.");
        }
        catch (Exception ex)
        {
            logger.LogWarning(
                ex,
                "No se pudo conectar o inicializar PostgreSQL durante el arranque. Verifique la cadena de conexión en appsettings.Development.json.");
        }
    }

    /// <summary>
    /// Crea las tablas del esquema <c>public</c> si no existen y sincroniza los tipos documentales y sus reglas.
    /// </summary>
    /// <param name="dbContext">Contexto de base de datos activo.</param>
    /// <param name="validators">Validadores registrados cuyas reglas se registrarán en el catálogo.</param>
    public static async Task SeedCatalogAsync(
        VeridocDbContext dbContext,
        IEnumerable<IDocumentValidator> validators)
    {
        await dbContext.Database.ExecuteSqlRawAsync(EnsurePublicSchemaSql);

        foreach (IDocumentValidator validator in validators)
        {
            TipoDocumento? tipoDoc = await dbContext.TiposDocumento
                .Include(t => t.Reglas)
                .FirstOrDefaultAsync(t => t.Codigo == validator.DocumentType);

            if (tipoDoc is null)
            {
                tipoDoc = new TipoDocumento
                {
                    Codigo = validator.DocumentType,
                    Nombre = validator.DisplayName,
                    Activo = true,
                    FechaCreacionUtc = DateTime.UtcNow
                };
                dbContext.TiposDocumento.Add(tipoDoc);
                await dbContext.SaveChangesAsync();
            }

            IReadOnlyList<RuleMetadataDto> rulesMetadata = validator.GetRulesMetadata();
            foreach (RuleMetadataDto ruleMeta in rulesMetadata)
            {
                bool exists = tipoDoc.Reglas.Any(r =>
                    string.Equals(r.Codigo, ruleMeta.Code, StringComparison.OrdinalIgnoreCase));

                if (!exists)
                {
                    dbContext.ReglasValidacion.Add(new ReglaValidacion
                    {
                        TipoDocumentoId = tipoDoc.Id,
                        Codigo = ruleMeta.Code,
                        Nombre = ruleMeta.Name,
                        Descripcion = ruleMeta.Description,
                        Activa = true
                    });
                }
            }

            await dbContext.SaveChangesAsync();
        }
    }
}
